// Writes server/src/a2ui-icons.ts (the A2UI Basic catalog's icon names drawn as Lucide path data) and copies
// it to mobile/src/a2uiIcons.ts. Run with lucide-static unpacked somewhere:
//   npm pack lucide-static@1.81.0 && tar xzf lucide-static-1.81.0.tgz
//   node scripts/icons/build-a2ui-icons.mjs <lucide-static package dir>
// Lucide is ISC (see THIRD_PARTY_NOTICES.md). Bundled, never fetched at runtime.
import fs from 'node:fs';
import path from 'node:path';

const luDir = process.argv[2];
if (!luDir) { console.error('usage: build-a2ui-icons.mjs <lucide-static dir>'); process.exit(1); }

/** A2UI icon name -> Lucide icon. */
const MAP = {
  accountCircle: 'circle-user-round', add: 'plus', arrowBack: 'arrow-left', arrowForward: 'arrow-right', attachFile: 'paperclip',
  calendarToday: 'calendar', call: 'phone', camera: 'camera', check: 'check', close: 'x', delete: 'trash-2', download: 'download',
  edit: 'pencil', event: 'calendar-days', error: 'circle-alert', fastForward: 'fast-forward', favorite: 'heart', favoriteOff: 'heart-off',
  folder: 'folder', help: 'circle-question-mark', home: 'house', info: 'info', locationOn: 'map-pin', lock: 'lock', lockOpen: 'lock-open',
  mail: 'mail', menu: 'menu', moreVert: 'ellipsis-vertical', moreHoriz: 'ellipsis', notificationsOff: 'bell-off', notifications: 'bell',
  pause: 'pause', payment: 'credit-card', person: 'user', phone: 'smartphone', photo: 'image', play: 'play', print: 'printer',
  refresh: 'refresh-cw', rewind: 'rewind', search: 'search', send: 'send', settings: 'settings', share: 'share-2',
  shoppingCart: 'shopping-cart', skipNext: 'skip-forward', skipPrevious: 'skip-back', star: 'star', starHalf: 'star-half', starOff: 'star-off',
  stop: 'square', upload: 'upload', visibility: 'eye', visibilityOff: 'eye-off', volumeDown: 'volume-1', volumeMute: 'volume', volumeOff: 'volume-x',
  volumeUp: 'volume-2', warning: 'triangle-alert',
};
const num = (s) => Number(s ?? 0);
const attrs = (tag) => Object.fromEntries([...tag.matchAll(/([a-z0-9-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
function toPath(tag) {
  const name = tag.match(/^<([a-z]+)/)[1];
  const a = attrs(tag);
  if (name === 'path') return a.d;
  if (name === 'line') return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
  if (name === 'polyline' || name === 'polygon') {
    const p = a.points.trim().split(/[\s,]+/);
    let d = `M${p[0]} ${p[1]}`;
    for (let i = 2; i < p.length; i += 2) d += `L${p[i]} ${p[i + 1]}`;
    return name === 'polygon' ? `${d}Z` : d;
  }
  if (name === 'circle' || name === 'ellipse') {
    const cx = num(a.cx), cy = num(a.cy), rx = num(a.r ?? a.rx), ry = num(a.r ?? a.ry);
    return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${rx * 2} 0a${rx} ${ry} 0 1 0 ${-rx * 2} 0`;
  }
  if (name === 'rect') {
    const x = num(a.x), y = num(a.y), w = num(a.width), h = num(a.height);
    const r = Math.min(num(a.rx ?? a.ry), w / 2, h / 2);
    if (!r) return `M${x} ${y}h${w}v${h}h${-w}Z`;
    return `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`;
  }
  throw new Error(`unknown shape ${name}`);
}
const lines = [];
for (const [name, lu] of Object.entries(MAP)) {
  const svg = fs.readFileSync(path.join(luDir, 'icons', `${lu}.svg`), 'utf8');
  const tags = [...svg.matchAll(/<(path|line|polyline|polygon|circle|ellipse|rect)\b[^>]*\/?>/g)].map((m) => m[0]);
  lines.push(`  ${name}: ${JSON.stringify(tags.map(toPath))},`);
}
const out = `/**
 * The A2UI Basic catalog's icon names (a2ui.ts) as path data on a 24 x 24 grid, stroked 2 wide with round ends,
 * so every app draws them the same with one <path> per entry. From Lucide (lucide-static 1.81.0, ISC); generated by
 * scripts/icons/build-a2ui-icons.mjs and copied word for word to mobile/src/a2uiIcons.ts.
 */
export const A2UI_ICON_PATHS: Record<string, string[]> = {
${lines.join('\n')}
};
`;
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
fs.writeFileSync(path.join(root, 'server/src/a2ui-icons.ts'), out);
fs.writeFileSync(path.join(root, 'mobile/src/a2uiIcons.ts'), out);
console.log(`${lines.length} icons`);
