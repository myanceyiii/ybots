// Bundles the computer-screen page (vnc/page.js + page.css + noVNC) into one HTML string the app loads in a
// WebView: src/vnc/page.generated.ts. Runs on `npm install` (postinstall) and with `npm run vnc`.
import { build } from 'esbuild';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = await build({
  entryPoints: [join(root, 'vnc/page.js')],
  bundle: true, minify: true, format: 'esm', target: 'chrome100', write: false, legalComments: 'inline',
});
const js = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const css = readFileSync(join(root, 'vnc/page.css'), 'utf8');
// Runs before noVNC binds its log to console.error: keeps noVNC's last failure line for page.js.
const failHook = `(function(){var e=console.error.bind(console);window.__cleftFail='';console.error=function(){var m=Array.prototype.map.call(arguments,String).join(' ');if(/^(Failed (when|while)|RFB failure)/.test(m))window.__cleftFail=m.slice(0,200);e.apply(null,arguments);};})();`;
const html = `<!doctype html><html><head><meta charset="utf-8"><script>${failHook}</script><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover"><style>${css}</style></head><body><div id="view"><div id="canvas"></div></div><div id="touch" hidden><textarea id="input" autocapitalize="off" autocomplete="off" autocorrect="off" spellcheck="false" enterkeyhint="enter" aria-label="Type on the screen"></textarea><div class="slot"></div></div><script type="module">${js}</script></body></html>`;
mkdirSync(join(root, 'src/vnc'), { recursive: true });
writeFileSync(join(root, 'src/vnc/page.generated.ts'), `// Generated by scripts/build-vnc.mjs from vnc/ and noVNC (MPL-2.0). Do not edit.\nexport const SCREEN_PAGE = ${JSON.stringify(html)};\n`);
console.log(`vnc page: ${(html.length / 1024).toFixed(0)} KB`);
